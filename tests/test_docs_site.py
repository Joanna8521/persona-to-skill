# -*- coding: utf-8 -*-
"""The documentation site, and the one way it could quietly lie.

A docs site that restates the README drifts from it, and drift in
documentation is this project's own subject: something that reads as a
guarantee while nothing holds it up. So every page under docs/ is generated by
tools/build_docs.py, and this file asserts the committed pages match what that
script produces right now.

Without this, the normal failure is invisible. Someone edits contract.py, the
reference page keeps describing the old value, the site builds cleanly, and
the page is wrong in the one direction that matters: it still looks
authoritative.
"""
import subprocess
import sys
from pathlib import Path

import _base  # noqa: F401

ROOT = Path(__file__).resolve().parent.parent
DOCS = ROOT / "docs"
BUILDER = ROOT / "tools" / "build_docs.py"


def test_the_builder_exists_and_names_its_targets():
    """A guard with nothing to guard passes forever."""
    assert BUILDER.exists()
    sys.path.insert(0, str(ROOT / "tools"))
    import build_docs  # noqa: PLC0415

    targets = build_docs.targets()
    assert targets, "build_docs.targets() is empty"
    # The three prose pages and the three extracted ones.
    assert set(targets) >= {
        "index.md", "zh-TW/index.md", "ja/index.md",
        "reference/contract.md", "reference/gates.md", "reference/cli.md",
    }, sorted(targets)


def test_every_generated_page_is_current():
    """`--check` is what CI runs; this runs the same thing."""
    result = subprocess.run(
        [sys.executable, "-I", str(BUILDER), "--check"],
        capture_output=True, text=True, cwd=str(ROOT),
    )
    # The message does not claim to know WHY the builder failed.
    #
    # The first version said "docs/ is out of date" for any non-zero exit, and
    # then the builder died on a Windows console encoding error while the
    # pages were perfectly current. A test that names the wrong cause sends
    # the next person to the wrong place, which is worse than one that just
    # shows the output.
    assert result.returncode == 0, (
        f"tools/build_docs.py --check failed (exit {result.returncode}). "
        f"If it says a page is out of date, run `python3 tools/build_docs.py`.\n"
        f"{result.stdout}{result.stderr}"
    )


def test_a_generated_page_says_it_is_generated():
    """Someone will open docs/reference/contract.md and start editing it.

    The header is the only thing that will stop them, so it has to be on every
    page rather than on the ones that happened to get it.
    """
    sys.path.insert(0, str(ROOT / "tools"))
    import build_docs  # noqa: PLC0415

    for rel in build_docs.targets():
        text = (DOCS / rel).read_text(encoding="utf-8")
        assert text.startswith("<!-- Generated by tools/build_docs.py"), rel


def test_the_readmes_do_not_leak_their_language_switcher():
    """The site header has a real switcher. Rendering the README's as well
    would put three dead links at the top of every home page, and they would
    point at .md files that are not on the site."""
    for rel in ("index.md", "zh-TW/index.md", "ja/index.md"):
        text = (DOCS / rel).read_text(encoding="utf-8")
        assert 'href="README' not in text, rel


def test_every_nav_target_in_mkdocs_yml_exists():
    """mkdocs runs with strict: true, so a missing target fails the build. But
    the build needs mkdocs installed, and these paths can be checked without
    it, so a contributor with no docs extras still finds out."""
    text = (ROOT / "mkdocs.yml").read_text(encoding="utf-8")
    missing = []
    for line in text.split("\n"):
        line = line.strip()
        if not line.startswith("- ") or ".md" not in line:
            continue
        target = line.split(":", 1)[-1].strip()
        if not target.endswith(".md"):
            continue
        if not (DOCS / target).exists():
            missing.append(target)
    assert not missing, f"nav points at pages that do not exist: {missing}"


def test_the_reference_pages_carry_the_real_values():
    """Extracted, not retyped.

    If the extraction silently produced empty sections the page would still
    build and still look like a reference, so a few values the contract really
    holds are checked for by name.
    """
    from persona_to_skill import contract  # noqa: PLC0415

    page = (DOCS / "reference" / "contract.md").read_text(encoding="utf-8")
    for name in ("HOLDOUT_MIN_ALIGNMENT", "SOURCE_TIERS", "SEATS",
                 "EVAL_RUN_REQUIRED_FIELDS"):
        assert f"`{name}`" in page, name
    # And the value itself, not only the name.
    assert str(contract.HOLDOUT_MIN_ALIGNMENT) in page

    gates = (DOCS / "reference" / "gates.md").read_text(encoding="utf-8")
    for gate in ("G1-consent", "G2-anchor", "G3-disclosure", "G4-holdout",
                 "G5-interrogation"):
        assert gate in gates, gate

    cli = (DOCS / "reference" / "cli.md").read_text(encoding="utf-8")
    for command in ("fetch", "import", "gates", "package", "eval", "punct"):
        assert f"## `{command}`" in cli, command


def test_published_comments_obey_the_prose_rules():
    """Publishing a comment puts it under the typography rules.

    `--` as an aside separator was the house style in Python comments, and the
    punctuation gate never saw it: that gate reads Markdown. Then the
    reference pages started extracting those comments INTO Markdown, and 23
    violations appeared in files nobody had written by hand.

    The honest fix was the source, not an exemption for the generated pages.
    This keeps it that way: contract.py and every module with a `check`
    function have their prose published, so they are held to the rule the
    published form is held to.

    Scoped to the modules that actually get extracted. Widening it to the
    whole package would be a different decision, and one nobody has argued
    for; narrowing it to "only the lines that happen to be extracted today"
    would leave a trap for the next value somebody adds.
    """
    import re  # noqa: PLC0415

    published = [ROOT / "persona_to_skill" / "contract.py"]
    for path in sorted((ROOT / "persona_to_skill").rglob("*.py")):
        src = path.read_text(encoding="utf-8")
        if re.search(r"^def check\(", src, re.M):
            published.append(path)

    dash = re.compile(r"(?<!-)-- ")
    hits = []
    for path in published:
        for n, line in enumerate(path.read_text(encoding="utf-8").split("\n"), 1):
            # Only prose. A command-line flag is not an em dash.
            if "--" not in line or re.search(r"--[a-z]", line):
                continue
            if dash.search(line):
                hits.append(f"{path.relative_to(ROOT)}:{n} {line.strip()[:70]}")

    assert not hits, (
        "`--` used as prose in a comment or docstring that the reference "
        f"pages publish: {hits}. The punctuation gate forbids it in Markdown, "
        "and these become Markdown. Use a comma, a colon, or parentheses."
    )


