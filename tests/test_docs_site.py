"""The documentation site, and the one way it could quietly lie.

A docs site that restates the README drifts from it, and drift in
documentation is this project's own subject: something that reads as a
guarantee while nothing holds it up. So every page under docs/ is generated by
tools/build_docs.py, and this file asserts the committed pages match what that
script produces right now.

Without this, the normal failure is invisible. Someone edits contract.py, the
reference page keeps describing the old value, the site builds cleanly, and
the page is wrong in the one direction that matters: it still looks
authoritative.
"""
import importlib.util
import re
import subprocess
import sys
import tempfile
from pathlib import Path

import _base  # noqa: F401

ROOT = Path(__file__).resolve().parent.parent
DOCS = ROOT / "docs"
BUILDER = ROOT / "tools" / "build_docs.py"


def test_the_builder_exists_and_names_its_targets():
    """A guard with nothing to guard passes forever."""
    assert BUILDER.exists()
    sys.path.insert(0, str(ROOT / "tools"))
    import build_docs  # noqa: PLC0415

    targets = build_docs.targets()
    assert targets, "build_docs.targets() is empty"
    # The three prose pages and the three extracted ones.
    assert set(targets) >= {
        "index.md", "zh-TW/index.md", "ja/index.md",
        "reference/contract.md", "reference/gates.md", "reference/cli.md",
    }, sorted(targets)


def test_every_generated_page_is_current():
    """`--check` is what CI runs; this runs the same thing."""
    result = subprocess.run(
        [sys.executable, "-I", str(BUILDER), "--check"],
        capture_output=True, text=True, cwd=str(ROOT),
    )
    # The message does not claim to know WHY the builder failed.
    #
    # The first version said "docs/ is out of date" for any non-zero exit, and
    # then the builder died on a Windows console encoding error while the
    # pages were perfectly current. A test that names the wrong cause sends
    # the next person to the wrong place, which is worse than one that just
    # shows the output.
    assert result.returncode == 0, (
        f"tools/build_docs.py --check failed (exit {result.returncode}). "
        f"If it says a page is out of date, run `python3 tools/build_docs.py`.\n"
        f"{result.stdout}{result.stderr}"
    )


def test_a_generated_page_says_it_is_generated():
    """Someone will open docs/reference/contract.md and start editing it.

    The header is the only thing that will stop them, so it has to be on every
    page rather than on the ones that happened to get it.
    """
    sys.path.insert(0, str(ROOT / "tools"))
    import build_docs  # noqa: PLC0415

    for rel in build_docs.targets():
        text = (DOCS / rel).read_text(encoding="utf-8")
        assert text.startswith("<!-- Generated by tools/build_docs.py"), rel


def test_no_page_links_to_a_markdown_file_in_raw_html():
    """mkdocs rewrites `[text](page.md)` to the built URL. It does not touch
    an href inside raw HTML, so one written there survives into the site and
    404s.

    This replaced a test that named three files and one spelling,
    `href="README`, and so missed the three journey pages, whose switcher was
    spelled `href="journey.md"`. Both halves of that test were a list, and a
    list stops being true the moment someone adds a file or writes the same
    mistake differently. Every page is walked here, and any href at all that
    points at a .md is a finding.

    The language switcher those links belonged to is redundant on the site:
    the i18n plugin puts a real one in the header, which the built HTML shows
    as `md-select` with links to every locale.
    """
    bad = []
    for page in sorted(DOCS.rglob("*.md")):
        for match in re.finditer(r'<a\s[^>]*href="([^"]+)"', page.read_text(encoding="utf-8")):
            target = match.group(1)
            path = target.split("#", 1)[0].split("?", 1)[0]
            if path.endswith(".md"):
                bad.append(f"{page.relative_to(DOCS)} -> {target}")
    assert not bad, (
        "raw-HTML links to .md files survive into the built site and 404 "
        "there:\n  " + "\n  ".join(bad))


def test_every_nav_target_in_mkdocs_yml_exists():
    """mkdocs runs with strict: true, so a missing target fails the build. But
    the build needs mkdocs installed, and these paths can be checked without
    it, so a contributor with no docs extras still finds out."""
    text = (ROOT / "mkdocs.yml").read_text(encoding="utf-8")
    missing = []
    for line in text.split("\n"):
        line = line.strip()
        if not line.startswith("- ") or ".md" not in line:
            continue
        target = line.split(":", 1)[-1].strip()
        if not target.endswith(".md"):
            continue
        if not (DOCS / target).exists():
            missing.append(target)
    assert not missing, f"nav points at pages that do not exist: {missing}"


def test_the_reference_pages_carry_the_real_values():
    """Extracted, not retyped.

    If the extraction silently produced empty sections the page would still
    build and still look like a reference, so a few values the contract really
    holds are checked for by name.
    """
    from persona_to_skill import contract  # noqa: PLC0415

    page = (DOCS / "reference" / "contract.md").read_text(encoding="utf-8")
    for name in ("HOLDOUT_MIN_ALIGNMENT", "SOURCE_TIERS", "SEATS",
                 "EVAL_RUN_REQUIRED_FIELDS"):
        assert f"`{name}`" in page, name
    # And the value itself, not only the name.
    assert str(contract.HOLDOUT_MIN_ALIGNMENT) in page

    gates = (DOCS / "reference" / "gates.md").read_text(encoding="utf-8")
    for gate in ("G1-consent", "G2-anchor", "G3-disclosure", "G4-holdout",
                 "G5-interrogation"):
        assert gate in gates, gate

    cli = (DOCS / "reference" / "cli.md").read_text(encoding="utf-8")
    for command in ("fetch", "import", "gates", "package", "eval", "punct"):
        assert f"## `{command}`" in cli, command


def test_published_comments_obey_the_prose_rules():
    """Publishing a comment puts it under the typography rules.

    `--` as an aside separator was the house style in Python comments, and the
    punctuation gate never saw it: that gate reads Markdown. Then the
    reference pages started extracting those comments INTO Markdown, and 23
    violations appeared in files nobody had written by hand.

    The honest fix was the source, not an exemption for the generated pages.
    This keeps it that way: contract.py and every module with a `check`
    function have their prose published, so they are held to the rule the
    published form is held to.

    Scoped to the modules that actually get extracted. Widening it to the
    whole package would be a different decision, and one nobody has argued
    for; narrowing it to "only the lines that happen to be extracted today"
    would leave a trap for the next value somebody adds.
    """
    import re  # noqa: PLC0415

    published = [ROOT / "persona_to_skill" / "contract.py"]
    for path in sorted((ROOT / "persona_to_skill").rglob("*.py")):
        src = path.read_text(encoding="utf-8")
        if re.search(r"^def check\(", src, re.M):
            published.append(path)

    dash = re.compile(r"(?<!-)-- ")
    hits = []
    for path in published:
        for n, line in enumerate(path.read_text(encoding="utf-8").split("\n"), 1):
            # Only prose. A command-line flag is not an em dash.
            if "--" not in line or re.search(r"--[a-z]", line):
                continue
            if dash.search(line):
                hits.append(f"{path.relative_to(ROOT)}:{n} {line.strip()[:70]}")

    assert not hits, (
        "`--` used as prose in a comment or docstring that the reference "
        f"pages publish: {hits}. The punctuation gate forbids it in Markdown, "
        "and these become Markdown. Use a comma, a colon, or parentheses."
    )




def test_every_built_page_has_a_sitemap_beside_it():
    """Material fetches `sitemap.xml` relative to every `<link rel=alternate>`,
    and the i18n plugin points those at the same page in each locale. On
    `/journey/` that is three requests, for `journey/sitemap.xml` and the two
    translated ones, none of which the plugin writes. Material swallows the
    error, so the only symptom was a console full of 404s on every page view.

    This builds the site and checks the artefact rather than the hook, because
    the first version of the hook copied the sitemap into the three locale
    ROOTS. That silenced the home page and left every sub-page broken, and a
    test of the hook's intent would have passed.
    """
    # Asked of the interpreter that will run the build, not of PATH. The
    # first version used shutil.which("mkdocs"), which answers a different
    # question: in a virtualenv without mkdocs but with a system mkdocs still
    # on PATH, which() says yes and `sys.executable -m mkdocs` then fails with
    # "No module named mkdocs". A precondition has to test the thing the test
    # actually does.
    if importlib.util.find_spec("mkdocs") is None:
        import pytest  # noqa: PLC0415
        pytest.skip("mkdocs is not importable by this interpreter")

    with tempfile.TemporaryDirectory() as tmp:
        built = Path(tmp) / "site"
        result = subprocess.run(
            [sys.executable, "-m", "mkdocs", "build", "-d", str(built)],
            cwd=ROOT, capture_output=True, text=True, check=False)
        assert result.returncode == 0, result.stdout + result.stderr

        pages = sorted(built.rglob("index.html"))
        assert pages, "the build produced no pages"
        missing = [str(p.parent.relative_to(built))
                   for p in pages if not (p.parent / "sitemap.xml").exists()]
        assert not missing, (
            f"{len(missing)} of {len(pages)} built pages have no sitemap "
            f"beside them, so Material will 404 on each page view: {missing}")


# The spelling of the count in each README. The test below discovers every
# README*.md in the repository root and fails when one has no entry here, so
# this mapping cannot quietly fall behind the set of translations.
SUBCOMMAND_COUNT_PATTERNS = {
    "README.md": r"\b(One|Two|Three|Four|Five|Six|Seven|Eight|Nine|Ten) subcommands\b",
    "README.zh-TW.md": r"([一二三四五六七八九十])個子指令",
    "README.ja.md": r"サブコマンドは\s*(\d+)\s*つ",
}

_WORDS = {
    "one": 1, "two": 2, "three": 3, "four": 4, "five": 5,
    "six": 6, "seven": 7, "eight": 8, "nine": 9, "ten": 10,
    "一": 1, "二": 2, "三": 3, "四": 4, "五": 5,
    "六": 6, "七": 7, "八": 8, "九": 9, "十": 10,
}


def _parser_subcommand_count():
    import argparse  # noqa: PLC0415

    from persona_to_skill.cli import build_parser  # noqa: PLC0415

    parser = build_parser()
    subs = [a for a in parser._actions
            if isinstance(a, argparse._SubParsersAction)]
    assert len(subs) == 1, "expected exactly one subparsers action"
    return len(subs[0].choices)


def test_every_readme_states_the_real_number_of_subcommands():
    """Three READMEs said five after `punct` made it six.

    Nothing recomputed it, so the number sat there being wrong in three
    languages at once. A figure written in prose and never recomputed is the
    same shape of defect as a gate that cannot fail, which is the thing this
    repository is about: it reads as a fact and costs nothing to be wrong.
    """
    import re as _re  # noqa: PLC0415

    expected = _parser_subcommand_count()
    wrong = []

    # Discovered, not listed. The first version of this test iterated the
    # mapping's own keys, so a README.fr.md would have been invisible to it
    # while the comment above promised the opposite.
    readmes = sorted(p.name for p in ROOT.glob("README*.md"))
    assert readmes, "no README found at the repository root"
    unconfigured = [n for n in readmes if n not in SUBCOMMAND_COUNT_PATTERNS]
    assert not unconfigured, (
        f"these READMEs have no subcommand-count pattern, so nothing checks "
        f"their figure: {unconfigured}. Add one to "
        f"SUBCOMMAND_COUNT_PATTERNS.")

    for name in readmes:
        pattern = SUBCOMMAND_COUNT_PATTERNS[name]
        text = (ROOT / name).read_text(encoding="utf-8")
        match = _re.search(pattern, text)
        if match is None:
            wrong.append(f"{name}: no subcommand count found at all "
                         f"(pattern {pattern!r} matched nothing)")
            continue
        token = match.group(1)
        found = _WORDS.get(token.lower(), None)
        if found is None:
            found = int(token) if token.isdigit() else None
        if found != expected:
            wrong.append(f"{name}: says {token} ({found}), parser has {expected}")

    assert not wrong, "\n  ".join([""] + wrong)

