#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Generate the documentation site's pages from the repository itself.

    python3 tools/build_docs.py           # write
    python3 tools/build_docs.py --check   # compare only, non-zero on drift

### Why generate rather than write

A docs site that restates the README will drift from it, and drift in
documentation is the same failure this project is built around: something that
reads as a guarantee while nothing holds it up. So nothing here is written
twice.

    docs/index.md            the README, minus the front matter GitHub needs
                             and the site does not
    docs/reference/*.md      extracted from the code, so they cannot be wrong
                             about the code

The reference pages are the site's reason to exist. The frozen contract, the
gates and their reasoning, and the command line are all things a reader wants
laid out in one place, and all three are already stated precisely in the
source. Copying them into prose would create a second version to maintain;
extracting them means a stale page is a failing check rather than a quiet lie.

### The reference pages are English only, deliberately

Their content is lifted from docstrings and comments, which are in English.
Hand-translating extracted text would produce three versions drifting from the
code at three different rates. mkdocs-static-i18n falls back to the default
language for a page a translation does not have, which is the honest outcome:
the prose pages are fully translated, the extracted ones do not pretend to be.
"""
from __future__ import annotations

import ast
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DOCS = ROOT / "docs"
PKG = ROOT / "persona_to_skill"

# (README, where it goes). The folder layout is what mkdocs-static-i18n calls
# `docs_structure: folder`, and it is also where the journey pages already
# live, so the punctuation gate's PUNCT_CHECKED_DIRS keeps working unchanged.
READMES = [
    ("README.md", "index.md"),
    ("README.zh-TW.md", "zh-TW/index.md"),
    ("README.ja.md", "ja/index.md"),
]

GENERATED = (
    "<!-- Generated by tools/build_docs.py. Edit the source, not this file. -->"
)

REPO_BLOB = "https://github.com/Joanna8521/persona-to-skill/blob/main/"

SITE = "https://joanna8521.github.io/persona-to-skill/"

# Two blocks at the top of each README that the site must not render.
#
# The language switcher, because the site header has a real one and these
# point at .md files that are not on the site.
#
# The documentation links, because on the site they point back at the page
# they are on and at three pages already in the navigation. They exist for
# readers who arrived on GitHub.
SWITCHER = re.compile(
    r"<p align=\"center\">\s*\n(?:\s*<a href=\"README[^\"]*\">[^\n]*\n)+\s*</p>\n",
    re.S,
)
SITE_LINKS = re.compile(
    r"<p align=\"center\">\s*\n(?:\s*<a href=\"" + re.escape(SITE)
    + r"[^\"]*\">[^\n]*\n)+\s*</p>\n",
    re.S,
)


def _readme_to_page(text: str) -> str:
    """The README as a site page.

    Three changes, each for a reason the site makes necessary:

    * the language switcher and the documentation links go, because the site
      header has a real switcher and those links point back at this page;
    * `<h1 align="center">` becomes a Markdown h1, because mkdocs takes the
      page title and the navigation entry from the first Markdown heading, and
      an HTML one leaves both empty;
    * links to files in the repository become links to GitHub, because
      `examples/eval/` is not a path on the site.
    """
    text = SWITCHER.sub("", text)
    text = SITE_LINKS.sub("", text)
    text = re.sub(r'<h1 align="center">(.*?)</h1>', r"# \1", text)
    text = re.sub(r"\]\((examples/[^)]*|[A-Z][A-Z_]*\.md)\)",
                  r"](" + REPO_BLOB + r"\1)", text)
    # The rule under the tagline separates front matter from body on GitHub.
    # On the site the header already does that.
    text = text.replace("\n---\n\n## ", "\n## ", 1)
    return GENERATED + "\n\n" + text.lstrip("\n")


# ── the frozen contract ─────────────────────────────────

def _contract_entries():
    """Every upper-case assignment in contract.py, with the comment above it.

    The comments are the contract. A table of names and values would leave out
    the reasoning, which is the part a reader actually needs, so the comment
    block immediately above each assignment is carried across with it.
    """
    src = (PKG / "contract.py").read_text(encoding="utf-8")
    lines = src.split("\n")
    out = []
    for node in ast.parse(src).body:
        if not isinstance(node, ast.Assign) or len(node.targets) != 1:
            continue
        target = node.targets[0]
        if not isinstance(target, ast.Name) or not target.id.isupper():
            continue

        comment = []
        i = node.lineno - 2
        while i >= 0:
            line = lines[i].rstrip()
            if not line.startswith("#"):
                break
            body = line[1:].strip()
            if body and set(body) <= {"-"}:   # a section rule, not prose
                break
            comment.append(body)
            i -= 1
        comment.reverse()

        end = node.end_lineno or node.lineno
        out.append((target.id, comment, "\n".join(lines[node.lineno - 1:end])))
    return out


def _contract_page() -> str:
    from persona_to_skill import contract  # noqa: PLC0415

    entries = {n: (c, v) for n, c, v in _contract_entries()}
    frozen = set(contract.FROZEN)
    provisional = set(contract.PROVISIONAL)
    declared = set(contract.DECLARED)

    tier_table = [
        "| Tier | What it means |",
        "|------|---------------|",
        ("| **FROZEN** | Measured or argued for, and read by code. A test "
         "asserts each one is named in the registry and read somewhere "
         "outside the contract module, so a value cannot be added and left "
         "unwired, or wired and left out. |"),
        ("| **PROVISIONAL** | Read by code, and the number is still a guess. "
         "Each carries what would settle it. Collected in one place because "
         "keeping them only in the contract module was half the idea: the "
         "guesses had simply scattered into the modules that used them, which "
         "is harder to notice rather than better. |"),
        ("| **DECLARED** | Prose. No code reads it for a decision, and a test "
         "asserts these are *not* in FROZEN, so the distinction cannot quietly "
         "collapse. |"),
    ]

    intro = (
        "Every value `persona_to_skill/contract.py` holds, in the three tiers "
        "that module itself distinguishes. This page is extracted from that "
        "file, so it cannot disagree with it."
    )

    lines = [GENERATED, "", "# The frozen contract", "", intro, ""]
    lines += tier_table + [""]

    def section(title: str, names, note: str = "") -> None:
        lines.extend([f"## {title}", ""])
        if note:
            lines.extend([note, ""])
        for name in sorted(names):
            if name not in entries:
                continue
            comment, value = entries[name]
            lines.extend([f"### `{name}`", ""])
            if comment:
                lines.extend(["\n".join(comment).strip(), ""])
            if name in provisional:
                lines.extend([f"> **Provisional.** What would settle it: "
                              f"{contract.PROVISIONAL[name]}.", ""])
            lines.extend(["```python", value, "```", ""])

    section("FROZEN", frozen - provisional)
    section("PROVISIONAL", frozen & provisional,
            "Read by code, and the numbers are guesses. Each says what would "
            "replace it with a measurement.")
    section("DECLARED", declared, "Prose, read by nothing for a decision.")
    return "\n".join(lines)


# ── the gates ───────────────────────────────────────────

def _gate_modules():
    """Every module exposing a `check` function, with its module docstring."""
    out = []
    for path in sorted(PKG.rglob("*.py")):
        if path.name == "__init__.py":
            continue
        tree = ast.parse(path.read_text(encoding="utf-8"))
        if not any(isinstance(n, ast.FunctionDef) and n.name == "check"
                   for n in tree.body):
            continue
        gate = ""
        for n in tree.body:
            if (isinstance(n, ast.Assign) and len(n.targets) == 1
                    and isinstance(n.targets[0], ast.Name)
                    and n.targets[0].id == "GATE"
                    and isinstance(n.value, ast.Constant)):
                gate = str(n.value.value)
        out.append((path.relative_to(ROOT).as_posix(), gate,
                    ast.get_docstring(tree) or ""))
    return out


def _gates_page() -> str:
    intro = (
        "Every module that exposes a `check` function, with the reasoning it "
        "carries in its own docstring. This page is extracted from those "
        "modules, so a gate cannot be described here and absent there."
    )
    discipline = (
        "Each gate recomputes independently, fails closed when an input it "
        "depends on is missing, and reads the artifact actually being "
        "delivered rather than a fixture. Each has negative tests that must go "
        "red on a deliberately broken input: a gate that cannot fail is worse "
        "than no gate, because it grants confidence nothing earned."
    )
    lines = [GENERATED, "", "# The gates", "", intro, "", discipline, ""]
    for path, gate, doc in _gate_modules():
        lines.extend([f"## `{gate or Path(path).stem}`", "", f"`{path}`", ""])
        if doc:
            lines.extend([doc.strip(), ""])
    return "\n".join(lines)


# ── the command line ────────────────────────────────────

def _cli_page() -> str:
    from persona_to_skill import cli  # noqa: PLC0415

    parser = cli.build_parser()
    intro = (
        "Extracted from the argument parser, so an option cannot be documented "
        "here and missing there. Every subcommand wraps a function that already "
        "existed and was already tested: a command line carrying judgement of "
        "its own is a second implementation, and the two drift."
    )
    exits = (
        "**The exit code is the whole point of it being a command.** 0 means "
        "the gate passed; non-zero means it did not. Anything that prints a "
        "verdict and exits 0 is a gate that cannot be put in a CI job, which "
        "is the same as not having one. A bare `persona-to-skill` with no "
        "subcommand exits non-zero too, because a command that succeeds having "
        "done nothing is the same failure in miniature."
    )
    lines = [GENERATED, "", "# The command line", "", intro, "", exits, "",
             "```", parser.format_help().rstrip(), "```", ""]
    subs = next(a for a in parser._actions
                if hasattr(a, "choices") and a.choices)
    for name, sub in sorted(subs.choices.items()):
        lines.extend([f"## `{name}`", "", "```",
                      sub.format_help().rstrip(), "```", ""])
    return "\n".join(lines)


# ── driver ──────────────────────────────────────────────

def targets() -> dict:
    out = {}
    for readme, page in READMES:
        out[page] = _readme_to_page((ROOT / readme).read_text(encoding="utf-8"))
    out["reference/contract.md"] = _contract_page()
    out["reference/gates.md"] = _gates_page()
    out["reference/cli.md"] = _cli_page()
    return out


def main(argv) -> int:
    check = "--check" in argv
    bad = 0
    for rel, want in targets().items():
        path = DOCS / rel
        if not want.endswith("\n"):
            want += "\n"
        if check:
            have = path.read_text(encoding="utf-8") if path.exists() else ""
            if have != want:
                bad += 1
                why = "does not exist" if not path.exists() else "is out of date"
                print(f"  ❌ docs/{rel} {why}"
                      f" (run python3 tools/build_docs.py)")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(want, encoding="utf-8")
            print(f"  ✅ docs/{rel}　{len(want.splitlines())} lines")
    if check:
        print("  ✅ every generated page is current" if not bad
              else f"  {bad} page(s) out of date")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
